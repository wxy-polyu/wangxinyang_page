function getDictionary(lang) {
  return translations[lang] || translations.en;
}

function t(lang, key) {
  return getDictionary(lang)[key] || "";
}

function getInitialLanguage() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === "zh" || saved === "en") {
    return saved;
  }
  const browserLang = (navigator.language || navigator.userLanguage || "en").toLowerCase();
  return browserLang.startsWith("zh") ? "zh" : "en";
}

function createExternalLink(href, label, className) {
  const link = document.createElement("a");
  link.className = className;
  link.href = href;
  link.target = "_blank";
  link.rel = "noopener noreferrer";
  link.textContent = label;
  return link;
}

function renderProjects(lang) {
  projectGrid.replaceChildren();

  PROJECTS.forEach((project) => {
    const card = document.createElement("article");
    card.className = `project-card section-card${project.featured ? " featured" : ""}`;

    const kicker = document.createElement("p");
    kicker.className = "text-sm font-semibold uppercase tracking-[0.14em] text-gold";
    kicker.textContent = project.featured
      ? `${t(lang, "projects.featured")} · ${t(lang, `projects.${project.id}.kicker`)}`
      : t(lang, `projects.${project.id}.kicker`);

    const title = document.createElement("h3");
    title.className = "mt-2 font-serif text-2xl font-semibold text-pine";
    title.textContent = t(lang, `projects.${project.id}.title`);

    const desc = document.createElement("p");
    desc.className = "mt-3 leading-relaxed text-muted";
    desc.textContent = t(lang, `projects.${project.id}.desc`);

    const meta = document.createElement("p");
    meta.className = "project-meta";
    meta.textContent = t(lang, `projects.${project.id}.meta`);

    const tags = document.createElement("div");
    tags.className = "tag-list";
    project.tags.forEach((tagName) => {
      const tag = document.createElement("span");
      tag.className = "tag";
      tag.textContent = tagName;
      tags.appendChild(tag);
    });

    const actions = document.createElement("div");
    actions.className = "project-actions";
    if (project.demo) {
      actions.appendChild(createExternalLink(project.demo, t(lang, "projects.demo"), "btn-primary"));
    }
    if (project.source) {
      actions.appendChild(createExternalLink(project.source, t(lang, "projects.source"), "btn-secondary"));
    }

    card.append(kicker, title, desc, meta, tags);
    if (actions.childElementCount) {
      card.appendChild(actions);
    }
    projectGrid.appendChild(card);
  });
}

function applyTranslations(lang) {
  const dictionary = getDictionary(lang);
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (dictionary[key]) {
      if (element.tagName === "TITLE") {
        document.title = dictionary[key];
      } else {
        element.textContent = dictionary[key];
      }
    }
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const key = element.getAttribute("data-i18n-aria");
    if (dictionary[key]) {
      element.setAttribute("aria-label", dictionary[key]);
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.getAttribute("data-i18n-alt");
    if (dictionary[key]) {
      element.setAttribute("alt", dictionary[key]);
    }
  });

  renderProjects(lang);
}

function setLanguage(lang) {
  const nextLang = lang === "zh" ? "zh" : "en";
  localStorage.setItem(LANG_KEY, nextLang);
  document.documentElement.lang = nextLang === "zh" ? "zh-CN" : "en";
  applyTranslations(nextLang);
  updateMenuLabel();
  document.querySelectorAll(".lang-btn").forEach((button) => {
    const isActive = button.dataset.lang === nextLang;
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function isMenuOpen() {
  return menuToggle.getAttribute("aria-expanded") === "true";
}

function updateMenuLabel() {
  const lang = localStorage.getItem(LANG_KEY) || getInitialLanguage();
  const key = isMenuOpen() ? "nav.close" : "nav.menu";
  menuToggle.setAttribute("aria-label", t(lang, key));
}

function closeMenu() {
  menuToggle.setAttribute("aria-expanded", "false");
  mobileMenu.hidden = true;
  updateMenuLabel();
}

function openMenu() {
  menuToggle.setAttribute("aria-expanded", "true");
  mobileMenu.hidden = false;
  updateMenuLabel();
}

function toggleMenu() {
  if (isMenuOpen()) {
    closeMenu();
  } else {
    openMenu();
  }
}

function showPhotoFallback() {
  profilePhoto.hidden = true;
  profileFallback.hidden = false;
  profileFallback.removeAttribute("aria-hidden");
}

